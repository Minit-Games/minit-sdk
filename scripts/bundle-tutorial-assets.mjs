/**
 * Embeds tutorial pill assets (OK-button SVG, SFX) as data URIs so they work
 * when the SDK is consumed through Vite/Rollup pre-bundling — import.meta.url
 * relative paths break once deps land in node_modules/.vite/deps/.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assetsDir = join(root, 'src', 'modules', 'tutorial', 'assets');

function dataUri(mime, filePath) {
	const b64 = readFileSync(filePath).toString('base64');
	return `data:${mime};base64,${b64}`;
}

const okButtonImgUrl = dataUri(
	'image/svg+xml',
	join(assetsDir, 'button_ok_tutorial.svg'),
);
const popInSoundUrl = dataUri(
	'audio/mpeg',
	join(assetsDir, 'sfx', 'coffee-tin-lid-open-kawaii-ui.mp3'),
);
const okSoundUrl = dataUri(
	'audio/mpeg',
	join(assetsDir, 'sfx', 'button-plastic-tiny.mp3'),
);

const out = join(assetsDir, 'bundled.js');

writeFileSync(
	out,
	`// AUTO-GENERATED by scripts/bundle-tutorial-assets.mjs — do not edit.
export const okButtonImgUrl = ${JSON.stringify(okButtonImgUrl)};
export const popInSoundUrl = ${JSON.stringify(popInSoundUrl)};
export const okSoundUrl = ${JSON.stringify(okSoundUrl)};
`,
);

console.log('Wrote', out);
